import { chromium, firefox, expect, test } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
test('owned real study room, canonical reader, annotation and recoverable note',async()=>{
  const browserName=process.env.MATHMONGO_STUDY_BROWSER ?? 'chrome';
  const browser=browserName==='firefox'?await firefox.launch({headless:true}):await chromium.launch({headless:true,executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
  const context=await browser.newContext({viewport:{width:1366,height:768},reducedMotion:'reduce'});
  const page=await context.newPage();page.setDefaultTimeout(20000);
  const evidence=process.env.MATHMONGO_MAP_TEST_EVIDENCE,errors=[];
  const progress=async(text)=>writeFile(`${evidence}/room-progress.log`,text+'\n',{flag:'a'});
  page.on('pageerror',e=>errors.push(e.message));
  await context.route('**/*',route=>['localhost','127.0.0.1'].includes(new URL(route.request().url()).hostname)?route.continue():route.abort());
  try{
    await page.goto(process.env.MATHMONGO_MAP_TEST_URL);
    const nav=page.getByRole('combobox',{name:'Navegación',exact:true});await nav.click({timeout:60000});await nav.fill('Habitación de estudio');
    await page.getByRole('option').filter({hasText:'Habitación de estudio'}).click();
    const room=page.getByRole('region',{name:'Habitación de estudio',exact:true});
    await expect(room).toBeVisible();await expect(room.locator('.room-sphere')).toHaveCount(2);
    await expect(room).toContainText('Estudio temporal');await progress('loaded-two-saved-views');
    await room.getByRole('heading',{name:'Estudio temporal',exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:`${evidence}/room-general-1366.png`});
    await page.setViewportSize({width:1920,height:1080});await page.screenshot({path:`${evidence}/room-general-1920.png`});
    await page.setViewportSize({width:1366,height:768});
    await room.getByRole('button',{name:'Abrir fuente en el lector',exact:true}).click();
    await expect(page.getByRole('button',{name:'Volver a la habitación de estudio',exact:true})).toBeVisible();
    await expect(page.getByText('Paper temporal de la habitación',{exact:true}).first()).toBeVisible();
    await expect(page.getByRole('link',{name:'Abrir lector avanzado',exact:true})).toBeEnabled();
    const popupPromise=page.waitForEvent('popup');
    await page.getByRole('link',{name:'Abrir lector avanzado',exact:true}).click();
    const pdf=await popupPromise;
    try { await expect(pdf.locator('.page[data-page-number="1"] .textLayer span').first()).toBeVisible({timeout:20000}); } catch(error) { console.error('PDF URL',pdf.url(),await pdf.locator('body').innerText()); await pdf.screenshot({path:`${evidence}/pdf-failure.png`}); throw error; }
    expect(new URL(pdf.url()).searchParams.get('theme')).toBe('study');
    expect(await pdf.locator('body').evaluate(el=>getComputedStyle(el).backgroundColor)).toBe('rgb(9, 26, 39)');
    expect(await pdf.locator('.page canvas').first().evaluate(el=>getComputedStyle(el).filter)).toBe('none');
    await pdf.screenshot({path:`${evidence}/room-pdf-reader.png`});await pdf.close();
    await progress('canonical-reader-opened');
    await page.getByRole('button',{name:'Volver a la habitación de estudio',exact:true}).click();
    await expect(room).toBeVisible();
    await room.getByRole('combobox',{name:'Anotación o pasaje registrado',exact:true}).selectOption(process.env.MATHMONGO_ROOM_MARK_ID);
    await expect(room.locator('blockquote')).toHaveText('searchable theorem beta');
    await room.getByRole('button',{name:'Volver al pasaje exacto',exact:true}).click();
    await expect(page.getByRole('spinbutton',{name:'Página PDF',exact:true})).toHaveValue('2');
    await page.getByRole('button',{name:'Volver a la habitación de estudio',exact:true}).click();await expect(room).toBeVisible();
    await room.getByRole('button',{name:'Escribir nota desde este pasaje',exact:true}).click();
    let editor=page.locator('.editor-dialog');await expect(editor).toBeVisible();
    await expect(editor.getByRole('textbox',{name:'Documento visual',exact:true})).toContainText('searchable theorem beta');
    await editor.getByRole('textbox',{name:'Nombre',exact:true}).fill('Nota desde el paper');
    await editor.getByRole('button',{name:'Insertar fórmula en línea',exact:true}).click();
    await editor.getByRole('button',{name:'Fracción',exact:true}).click();
    await expect(editor.locator('[data-invalid="true"]')).toHaveCount(1);
    const mathSelection = await editor.locator('math-field').last().evaluate(field=>field.selection);
    await editor.getByRole('button',{name:'Conservar borrador y volver',exact:true}).click();
    await page.reload();await expect(room).toBeVisible();
    await room.getByRole('button',{name:'Nota desde el paper',exact:true}).click();await expect(editor).toBeVisible();
    await expect.poll(()=>editor.locator('math-field').last().evaluate(field=>field.selection)).toEqual(mathSelection);
    await expect.poll(()=>editor.locator('math-field').last().evaluate(field=>field.getRootNode().activeElement===field)).toBe(true);
    await page.keyboard.type('3');await page.keyboard.press('ArrowDown');await page.keyboard.type('4');
    await expect(editor.locator('[data-invalid="true"]')).toHaveCount(0);
    await editor.getByRole('button',{name:'Guardar nota',exact:true}).click();
    await editor.getByRole('button',{name:'Reconciliar envío del documento',exact:true}).click();
    await expect(editor).toHaveCount(0);
    await expect(room.getByRole('combobox',{name:'Nota personal',exact:true})).not.toHaveValue('');
    await progress('note-draft-recovered-and-saved');
    await room.getByRole('button',{name:'Comparar',exact:true}).click();
    await expect(room.locator('.room-compare-pane')).toHaveCount(2);
    await room.getByText('1 conceptos compartidos entre las dos vistas elegidas',{exact:true}).click();
    await room.getByRole('button',{name:/Slowly oscillating shift · Fuente de estudio temporal · nota:slow/}).click();
    await expect(room.locator('.room-compare-pane').first()).toContainText('Slowly oscillating shift');
    await expect(room.locator('.room-compare-pane').last()).toContainText('Slowly oscillating shift');
    await page.setViewportSize({width:420,height:900});
    await room.getByRole('button',{name:'Mostrar Contrastes',exact:true}).click();
    await expect(room.locator('.room-compare-pane').first()).toBeHidden();await expect(room.locator('.room-compare-pane').last()).toBeVisible();
    await room.screenshot({path:`${evidence}/room-compare-420.png`});
    await page.setViewportSize({width:1366,height:768});
    await room.getByRole('button',{name:'General',exact:true}).click();
    await room.getByRole('button',{name:'Análisis',exact:true}).click();
    await expect(page.locator('.expanded-map')).toBeVisible();
    await page.getByRole('button',{name:'Volver a la habitación',exact:true}).click();await expect(room.locator('.room-stage')).toBeVisible();
    const question=room.getByRole('combobox',{name:'Pregunta que completa esta nota (opcional)',exact:true});
    await question.selectOption({label:'¿Cómo se interpreta el pasaje?'});
    await room.getByRole('button',{name:'Incorporar nota como concepto…',exact:true}).click();
    await expect(editor).toBeVisible();
    await editor.getByRole('textbox',{name:'Nombre',exact:true}).fill('Concepto desde la nota');
    await editor.getByRole('button',{name:'Guardar concepto',exact:true}).click();await expect(editor).toHaveCount(0);
    let map=page.getByRole('region',{name:'Mapa de conocimiento editable',exact:true});
    await expect(map.getByRole('heading',{name:'Concepto desde la nota',exact:true})).toBeVisible();
    const publishedKey=await map.getByRole('combobox',{name:'Seleccionar concepto',exact:true}).inputValue();
    const views=()=>page.evaluate(()=>Object.fromEntries(Object.keys(localStorage).filter(k=>k.startsWith('mathmongo-map-v2-')).map(k=>{const v=JSON.parse(localStorage.getItem(k));return [v.mapName,v]})));
    const beforeViews=await views();
    const canvas=map.locator('canvas');await canvas.scrollIntoViewIfNeeded();
    const bounds=await canvas.boundingBox();
    await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);await page.mouse.down();
    await page.mouse.move(bounds.x+bounds.width/2+48,bounds.y+bounds.height/2-24,{steps:8});await page.mouse.up();
    await expect.poll(async()=>JSON.stringify((await views())['Análisis'].points[publishedKey])).not.toBe(JSON.stringify(beforeViews['Análisis'].points[publishedKey]));
    const movedViews=await views(), moved=movedViews['Análisis'].points[publishedKey];
    expect(Math.hypot(...moved)).toBeCloseTo(1,10);
    expect(movedViews['Contrastes'].points).toEqual(beforeViews['Contrastes'].points);
    await map.getByText('Más acciones',{exact:true}).click();
    await map.getByRole('button',{name:'Deshacer reubicación',exact:true}).click();
    expect((await views())['Análisis'].points[publishedKey]).toEqual(beforeViews['Análisis'].points[publishedKey]);
    await map.getByText('Más acciones',{exact:true}).click();
    await map.getByText('Reubicar y fijar nodo',{exact:true}).click();
    await map.getByRole('button',{name:'Mover nodo a la derecha',exact:true}).click();
    await canvas.screenshot({path:`${evidence}/room-node-moved.png`});

    if(!(await map.locator('.extra-actions').getAttribute('open'))) await map.getByText('Más acciones',{exact:true}).click();
    await map.getByRole('button',{name:'Guardar disposición',exact:true}).click();
    await expect(map.getByRole('status')).toContainText('guardad');
    await map.getByRole('button',{name:'Volver a la habitación',exact:true}).click();
    await room.getByRole('button',{name:'Contrastes',exact:true}).click();
    await map.getByRole('combobox',{name:'Seleccionar concepto',exact:true}).selectOption(publishedKey);
    await map.getByText('Más acciones',{exact:true}).click();
    await map.getByRole('button',{name:'Añadir concepto seleccionado a esta esfera',exact:true}).click();
    await map.getByRole('button',{name:'Guardar disposición',exact:true}).click();
    await expect(map.getByRole('status')).toContainText('guardad');
    await map.getByRole('button',{name:'Volver a la habitación',exact:true}).click();
    await expect(room.getByText('2 conceptos compartidos entre las dos vistas elegidas',{exact:true})).toBeVisible();
    const sphere=room.locator('.room-sphere').first();
    const previousPose=await sphere.evaluate(el=>[el.style.left,el.style.top]);
    await room.getByRole('button',{name:'Recolocar Análisis',exact:true}).press('ArrowRight');
    const savedPose=await sphere.evaluate(el=>[el.style.left,el.style.top]);
    expect(savedPose).not.toEqual(previousPose);
    await room.getByRole('button',{name:'Guardar habitación',exact:true}).click();
    await expect(room.getByRole('status')).toContainText('Habitación guardada');
    await page.reload();await expect(room).toBeVisible();
    await expect(room.getByText('2 conceptos compartidos entre las dos vistas elegidas',{exact:true})).toBeVisible();
    expect(await room.locator('.room-sphere').first().evaluate(el=>[el.style.left,el.style.top])).toEqual(savedPose);
    await progress('note-published-once-and-referenced-in-both-views');
    await room.getByRole('button',{name:'Análisis',exact:true}).click();
    await map.getByRole('combobox',{name:'Seleccionar concepto',exact:true}).selectOption(publishedKey);
    await map.getByRole('button',{name:'Leer concepto',exact:true}).click();
    const reading=page.locator('.reader-dialog');await expect(reading).toContainText('searchable theorem beta');
    await reading.getByRole('button',{name:'Volver al pasaje de la anotación',exact:true}).click();
    await expect(page.getByRole('spinbutton',{name:'Página PDF',exact:true})).toHaveValue('2');
    await page.getByRole('button',{name:'Volver a la habitación de estudio',exact:true}).click();
    await expect(map.getByRole('heading',{name:'Concepto desde la nota',exact:true})).toBeVisible();
    await progress('concept-canonical-evidence-returns-to-exact-page');
    expect(errors).toEqual([]);await writeFile(`${evidence}/room-browser.json`,JSON.stringify({browser:await browser.version(),errors,reader:true,noteRecovery:true,compareNarrow:true},null,2));
  }catch(error){await page.screenshot({path:`${evidence}/room-failure.png`,fullPage:true});console.error(await page.locator('body').innerText());throw error;}
  finally{await browser.close();}
});
