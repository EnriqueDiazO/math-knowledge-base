import test from "node:test";
import { chromium, firefox, expect } from "@playwright/test";
import { writeFile } from "node:fs/promises";
import { browserCoverage } from "./browser-coverage.mjs";
await test("Library source edit, shared bibliography, selective BibTeX and PDF-to-note persistence",{timeout:180000},async()=>{
 const name=process.env.MATHMONGO_STUDY_BROWSER||"chrome",base=process.env.MATHMONGO_INDEPENDENT_URL,evidence=process.env.MATHMONGO_INDEPENDENT_EVIDENCE;
 const browser=name==="firefox"?await firefox.launch({headless:true}):await chromium.launch({headless:true,executablePath:"/usr/bin/google-chrome",args:["--no-sandbox"]});
 const page=await browser.newPage({viewport:{width:1440,height:1080},reducedMotion:"reduce"});page.setDefaultTimeout(25000);
 const coverage=await browserCoverage(page,name,"library");let passed=false;
 const errors=[];page.on("pageerror",error=>errors.push(error.message));
 const button=name=>page.getByRole("button",{name,exact:true});
 const shot=name=>page.screenshot({path:evidence+"/library-"+name+".png",fullPage:true});
 const read=path=>page.evaluate(async path=>{const context=await(await fetch("/api/study/v1/context")).json();const result=await fetch("/api/study/v1"+path,{headers:{"X-MathMongo-Library":context.library_id}});if(!result.ok)throw new Error("Readback");return result.json();},path);
 try {
  await coverage.goto(base+"/study/library");
  await page.getByRole("link",{name:"+ Añadir fuente",exact:true}).click();
  await page.getByLabel("Nombre de la fuente",{exact:true}).fill("Fuente para administrar");
  await page.getByRole("combobox",{name:"Tipo de fuente",exact:true}).selectOption("web");
  await button("Guardar fuente").click();
  await expect(page.getByRole("heading",{name:"Fuente para administrar",exact:true})).toBeVisible();
  const sourceId=new URL(page.url()).pathname.split("/").at(-1),sourcePath=base+"/study/sources/"+sourceId;
  await coverage.reload();
  await button("Editar fuente").click();
  await page.getByLabel("Nombre de la fuente",{exact:true}).fill("Fuente corregida y recuperable");
  await page.getByLabel("Descripción",{exact:true}).fill("Descripción que debe persistir.");
  let lost=false;
  await page.route("**/sources/"+sourceId+"/profile",async route=>{
   if(route.request().method()==="POST"&&!lost){lost=true;const response=await route.fetch();expect(response.ok()).toBe(true);await route.abort("failed");}else await route.continue();
  });
  await button("Guardar cambios").click();
  await expect(button("Reintentar el mismo guardado")).toBeVisible();
  await coverage.reload();await button("Editar fuente").click();
  await button("Reintentar el mismo guardado").click();
  await expect(page.getByRole("heading",{name:"Fuente corregida y recuperable",exact:true})).toBeVisible();
  expect((await read("/sources/"+sourceId+"/profile")).description).toBe("Descripción que debe persistir.");
  await shot("source-edited-after-lost-reply");
  await button("+ Añadir referencia").click();
  await page.getByLabel("Título de la referencia",{exact:true}).fill("Referencia para compartir");
  await page.getByLabel("Autor u organización",{exact:true}).fill("Autora de ejemplo");
  await button("Guardar referencia").click();
  await expect(page.getByRole("heading",{name:"Referencia para compartir",exact:true})).toBeVisible();
  let detail=await read("/sources/"+sourceId);const referenceId=detail.references[0].reference_id;
  await button("Importar BibTeX").click();
  await page.getByLabel("Contenido BibTeX").fill("@article{One,title={Importada selectivamente},author={Noether, Emmy},year={1918}}\n@book{Two,title={No importar esta entrada},author={Ada},year={1843}}");
  await button("Revisar entradas BibTeX").click();
  await page.getByRole("checkbox",{name:/Importada selectivamente/}).check();
  await button("Importar referencias seleccionadas").click();
  await expect(page.getByRole("heading",{name:"Importada selectivamente",exact:true})).toBeVisible();
  expect((await read("/sources/"+sourceId)).references).toHaveLength(2);
  await shot("selected-bibtex");
  await button("+ Asociar documento").click();
  await page.getByLabel("Título del documento",{exact:true}).fill("Documento de Biblioteca");
  await page.getByRole("combobox",{name:"Referencia del documento",exact:true}).selectOption(referenceId);
  await page.getByLabel("Archivo PDF",{exact:true}).setInputFiles(process.env.MATHMONGO_AUTHORING_PDF);
  await button("Asociar documento").click();
  await expect(page.getByRole("heading",{name:"Documento de Biblioteca",exact:true})).toBeVisible();
  const documentId=(await read("/sources/"+sourceId)).documents[0].document_id;
  await button("Editar documento").click();
  await page.getByLabel("Título del documento",{exact:true}).fill("Documento corregido");
  await button("Guardar cambios").click();
  await expect(page.getByRole("heading",{name:"Documento corregido",exact:true})).toBeVisible();
  await page.getByText("Organizar documento",{exact:true}).click();
  await page.getByRole("checkbox",{name:"Confirmar archivar documento",exact:true}).check();
  await button("Archivar documento").click();
  await expect(page.getByRole("heading",{name:"Documento corregido",exact:true})).toHaveCount(0);
  await page.getByRole("combobox",{name:"Estado de los documentos",exact:true}).selectOption("archived");
  await expect(page.getByRole("heading",{name:"Documento corregido",exact:true})).toBeVisible();
  await page.getByText("Organizar documento",{exact:true}).click();
  await page.getByRole("checkbox",{name:"Confirmar reactivar documento",exact:true}).check();
  await button("Reactivar documento").click();
  await page.getByRole("combobox",{name:"Estado de los documentos",exact:true}).selectOption("active");
  await page.getByRole("link",{name:"Leer documento",exact:true}).click();
  const text=page.locator('.page[data-page-number="1"] .textLayer span').first();await expect(text).toBeVisible();
  await text.evaluate(element=>{const range=document.createRange();range.selectNodeContents(element);const selection=window.getSelection();selection.removeAllRanges();selection.addRange(range);element.dispatchEvent(new PointerEvent("pointerup",{bubbles:true}));document.dispatchEvent(new Event("selectionchange"));});
  await button("Escribir nota desde este pasaje").click();
  await page.getByLabel("Nombre de la nota",{exact:true}).fill("Nota de Biblioteca vinculada");
  await page.locator(".visual-document .tiptap").fill("Texto de la nota vinculado al documento corregido.");
  await button("Guardar nota").click();await expect(page).toHaveURL(/\/study\/notes\/note_/u);
  const noteId=new URL(page.url()).pathname.split("/").at(-1);
  await coverage.reload();await expect(page.locator(".visual-document .tiptap")).toContainText("Texto de la nota vinculado");
  await button("Incorporar como concepto").click();
  await expect(page.getByRole("heading",{name:"Nota de Biblioteca vinculada",exact:true})).toBeVisible();
  await coverage.goto(sourcePath);
  await page.getByRole("link",{name:"Conceptos de esta fuente",exact:true}).click();
  await expect(page.getByRole("link",{name:"Nota de Biblioteca vinculada",exact:true})).toBeVisible();
  await shot("source-concepts");
  await coverage.goto(sourcePath);await page.getByRole("link",{name:"Conceptos derivados del documento",exact:true}).click();
  await expect(page.getByRole("link",{name:"Nota de Biblioteca vinculada",exact:true})).toBeVisible();
  await coverage.goto(base+"/study/sources/new");
  await page.getByLabel("Nombre de la fuente",{exact:true}).fill("Segunda fuente con referencia compartida");await button("Guardar fuente").click();
  await expect(page.getByRole("heading",{name:"Segunda fuente con referencia compartida",exact:true})).toBeVisible();
  const secondSourceId=new URL(page.url()).pathname.split("/").at(-1);
  await button("+ Añadir referencia").click();
  await page.getByLabel("Consultar DOI o ISBN",{exact:true}).fill("Referencia para compartir");
  await button("Buscar en mis referencias").click();await button("Usar referencia existente").click();
  await button("Editar referencia").click();await page.getByLabel("Título de la referencia",{exact:true}).fill("Referencia compartida corregida");
  await page.getByRole("checkbox",{name:/Aplicar estos cambios a la referencia compartida/}).check();await button("Guardar cambios").click();
  await expect(page.getByRole("heading",{name:"Referencia compartida corregida",exact:true})).toBeVisible();
  await shot("shared-reference-edit");
  await coverage.goto(sourcePath);await button("Referencias").click();await expect(page.getByRole("heading",{name:"Referencia compartida corregida",exact:true})).toBeVisible();
  await page.setViewportSize({width:700,height:960});await shot("source-narrow");
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true);
  expect(errors).toEqual([]);passed=true;
  await writeFile(evidence+"/library-browser.json",JSON.stringify({passed,browser:name,version:browser.version(),sourceId,secondSourceId,referenceId,documentId,noteId,errors},null,2));
 } finally {if(!passed){await page.screenshot({path:evidence+"/library-failed.png",fullPage:true});await writeFile(evidence+"/library-failed-controls.json",JSON.stringify(await page.locator("label").allTextContents()));}await coverage.finish(passed);await browser.close();}
});
