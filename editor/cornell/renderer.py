def measure_cornell_page_fit(
    page: CornellPage,
    output_dir: str | Path,
    output_name: str,
    *,
    db: Any | None = None,
    assets_by_id: Mapping[str, Mapping[str, Any]] | None = None,
) -> PageFitReport:
    """Measure all regions in one Cornell page using the renderer preflight."""
    document = CornellDocument(schema_version=1, template_id="single_page_fit", pages=(page,))
    output_path, image_paths = _prepare_output_dir(
        output_dir,
        document,
        db=db,
        assets_by_id=assets_by_id,
    )
    fit_report = _preflight_cornell_fit(
        document,
        output_path,
        output_name,
        asset_paths_by_id=image_paths,
    )
    return fit_report.pages[0]


def render_cornell_pdf(
    page: CornellPage,
    output_dir: str | Path,
    *,
    db: Any | None = None,
    assets_by_id: Mapping[str, Mapping[str, Any]] | None = None,
) -> CornellRenderResult:
    """Render a single Cornell page directly to a PDF."""
    output_path = Path(output_dir)
    tex_path = output_path / f"cornell_{_slugify_page_id(page.page_id)}.tex"
    pdf_path = tex_path.with_suffix(".pdf")
    log_path = tex_path.with_suffix(".log")

    try:
        document = CornellDocument(schema_version=1, template_id="single_page_render", pages=(page,))
        output_path, image_paths = _prepare_output_dir(
            output_path,
            document,
            db=db,
            assets_by_id=assets_by_id,
        )
        fit_report = _preflight_cornell_fit(
            document,
            output_path,
            tex_path.stem,
            asset_paths_by_id=image_paths,
        )
        if fit_report.has_overflow:
            _remove_stale_pdf(pdf_path)
            return CornellRenderResult(
                success=False,
                status="overflow",
                tex_path=tex_path,
                pdf_path=pdf_path,
                log_path=log_path,
                message=_fit_overflow_message(fit_report),
                diagnostics=_fit_overflow_diagnostics(fit_report),
            )
        tex_path = _write_cornell_document_tex_with_assets(
            document,
            output_path,
            tex_path.stem,
            asset_paths_by_id=image_paths,
            fit_report=fit_report,
        )
        result = _compile_cornell_tex(tex_path, output_path)
        result.diagnostics["fit_report"] = fit_report.to_dict()
        return result
    except CornellLayoutError as exc:
        return CornellRenderResult(
            success=False,
            status="failed",
            tex_path=tex_path,
            pdf_path=pdf_path,
            log_path=log_path,
            message=str(exc),
            diagnostics=exc.diagnostics,
        )
    except Exception as exc:
        return CornellRenderResult(
            success=False,
            status="failed",
            tex_path=tex_path,
            pdf_path=pdf_path,
            log_path=log_path,
            message=str(exc),
            diagnostics={"exception_type": type(exc).__name__},
        )


def render_cornell_document(
    document: CornellDocument,
    output_dir: str | Path,
    output_name: str,
    *,
    db: Any | None = None,
    assets_by_id: Mapping[str, Mapping[str, Any]] | None = None,
) -> CornellRenderResult:
    """Render all Cornell pages into one LaTeX document and one PDF."""
    output_path = Path(output_dir)
    tex_path = output_path / f"{_slugify_output_name(output_name)}.tex"
    pdf_path = tex_path.with_suffix(".pdf")
    log_path = tex_path.with_suffix(".log")
    warnings: list[str] = []

    try:
        output_path, image_paths = _prepare_output_dir(
            output_path,
            document,
            db=db,
            assets_by_id=assets_by_id,
            warnings=warnings,
        )
        fit_report = _preflight_cornell_fit(
            document,
            output_path,
            output_name,
            asset_paths_by_id=image_paths,
        )
        if fit_report.has_overflow:
            _remove_stale_pdf(pdf_path)
            return CornellRenderResult(
                success=False,
                status="overflow",
                tex_path=tex_path,
                pdf_path=pdf_path,
                log_path=log_path,
                message=_fit_overflow_message(fit_report),
                diagnostics={
                    **_fit_overflow_diagnostics(fit_report),
                    "warnings": warnings,
                },
            )
        tex_path = _write_cornell_document_tex_with_assets(
            document,
            output_path,
            output_name,
            asset_paths_by_id=image_paths,
            fit_report=fit_report,
        )
        result = _compile_cornell_tex(tex_path, output_path)
        result.diagnostics["fit_report"] = fit_report.to_dict()
        result.diagnostics["warnings"] = warnings
        return result
    except CornellLayoutError as exc:
        return CornellRenderResult(
            success=False,
            status="failed",
            tex_path=tex_path,
            pdf_path=pdf_path,
            log_path=log_path,
            message=str(exc),
            diagnostics={**exc.diagnostics, "warnings": warnings},
        )
    except Exception as exc:
        return CornellRenderResult(
            success=False,
            status="failed",
            tex_path=tex_path,
            pdf_path=pdf_path,
            log_path=log_path,
            message=str(exc),
            diagnostics={"exception_type": type(exc).__name__, "warnings": warnings},
        )
