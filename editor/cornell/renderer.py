def _hybrid_region_body_latex(
    page: CornellPage,
    region_name: str,
    *,
    page_number: int,
    fit_report: CornellFitReport,
    asset_paths_by_id: Mapping[str, str] | None = None,
) -> str:
    """Render one region with the established content and image compatibility layer."""
    region = getattr(page, region_name)
    body = render_cornell_region_latex(
        region,
        region_name=region_name,
        asset_paths_by_id=asset_paths_by_id,
    )
    scale = fit_report.region_scale(page_number, region_name)
    marker = f"% Cornell source page={page_number} region={region_name}"
    return _scaled_region_latex(
        f"{marker}\n{body}",
        scale,
        content_width=HYBRID_REGION_CONTENT_WIDTHS[region_name],
    )


def _cornell_hybrid_sheet_page_body(
    document: CornellDocument,
    page: CornellPage,
    *,
    page_number: int,
    fit_report: CornellFitReport,
    asset_paths_by_id: Mapping[str, str] | None = None,
) -> str:
    """Render one continuous Cornell sheet with fixed semantic regions."""
    cue_heading = escape_latex_text(page.cue.heading or "Preguntas clave")
    main_heading = escape_latex_text(page.main.heading or "Contenido principal")
    summary_heading = escape_latex_text(page.summary.heading or "Síntesis")
    cue_body = _hybrid_region_body_latex(
        page,
        "cue",
        page_number=page_number,
        fit_report=fit_report,
        asset_paths_by_id=asset_paths_by_id,
    )
    main_body = _hybrid_region_body_latex(
        page,
        "main",
        page_number=page_number,
        fit_report=fit_report,
        asset_paths_by_id=asset_paths_by_id,
    )
    summary_body = _hybrid_region_body_latex(
        page,
        "summary",
        page_number=page_number,
        fit_report=fit_report,
        asset_paths_by_id=asset_paths_by_id,
    )
    return dedent(
        rf"""
        \null
        \begin{{tikzpicture}}[remember picture,overlay]
          \coordinate (SW) at (current page.south west);
          \coordinate (SE) at (current page.south east);
          \coordinate (NW) at (current page.north west);
          \coordinate (NE) at (current page.north east);

          \fill[CornellHybridCueSoft,opacity=.55] (NW) rectangle ($(SW)+(2.4in,2in)$);
          \fill[CornellHybridMainSoft,opacity=.30] ($(NW)+(2.4in,0)$) rectangle ($(SE)+(0,2in)$);
          \fill[CornellHybridSummarySoft,opacity=.65] (SW) rectangle ($(SE)+(0,2in)$);

          {cornell_watermark_latex(
              document,
              asset_paths_by_id=asset_paths_by_id,
              page_number=page_number,
          )}

          \foreach \y in {{2.35,2.70,...,10.55}}{{
            \draw[black!8,line width=.25pt] ($(SW)+(2.4in,\y in)$) -- ($(SE)+(0,\y in)$);
          }}
          \draw[line width=.65pt] ($(SW)+(0,2in)$) -- ($(SE)+(0,2in)$);
          \draw[line width=.65pt] ($(SW)+(2.4in,2in)$) -- ($(NW)+(2.4in,0)$);

          \begin{{scope}}
            \clip (NW) rectangle ($(SW)+(2.4in,2in)$);
            \node[anchor=north west,inner sep=0pt] at ($(NW)+(.16in,-.18in)$) {{%
              \begin{{minipage}}[t]{{{HYBRID_REGION_CONTENT_WIDTHS["cue"]}}}
                \CornellHybridCueHeading{{{cue_heading}}}
                {{\CornellHybridCueBody
                {cue_body}
                }}
              \end{{minipage}}%
            }};
          \end{{scope}}

          \begin{{scope}}
            \clip ($(NW)+(2.4in,0)$) rectangle ($(SE)+(0,2in)$);
            \node[anchor=north west,inner sep=0pt] at ($(NW)+(2.58in,-.14in)$) {{%
              \begin{{minipage}}[t]{{{HYBRID_REGION_CONTENT_WIDTHS["main"]}}}
                \CornellHybridMainHeading{{{main_heading}}}
                {{\CornellHybridMainBody
                {main_body}
                }}
              \end{{minipage}}%
            }};
          \end{{scope}}

          \begin{{scope}}
            \clip (SW) rectangle ($(SE)+(0,2in)$);
            \node[anchor=north west,inner sep=0pt] at ($(SW)+(.28in,1.78in)$) {{%
              \begin{{minipage}}[t]{{{HYBRID_REGION_CONTENT_WIDTHS["summary"]}}}
                \CornellHybridSummaryHeading{{{summary_heading}}}
                {{\CornellHybridSummaryBody
                {summary_body}
                }}
              \end{{minipage}}%
            }};
          \end{{scope}}

          {cornell_attribution_latex(document)}
        \end{{tikzpicture}}
        """
    ).strip() + "\n"


def _cornell_page_body(
    document: CornellDocument,
    page: CornellPage,
    *,
    page_number: int,
    fit_report: CornellFitReport,
    asset_paths_by_id: Mapping[str, str] | None = None,
    lines_image_path: str | None = LINES_IMAGE_INCLUDE_PATH,
) -> str:
    background_block = ""
    if lines_image_path:
        background_block = rf"""
        \begin{{scope}}
          \clip ($(SW)+(2.5in,2in)$) rectangle (NE);
          \node[anchor=north west, inner sep=0pt, opacity=.2] at ($(NW)+(2.5in,-1.11in)$)
            {{\includegraphics[width=6in]{{{lines_image_path}}}}};
        \end{{scope}}
        """

    return dedent(
        rf"""
        \null
        \begin{{tikzpicture}}[remember picture,overlay]
          \coordinate (SW) at (current page.south west);
          \coordinate (SE) at (current page.south east);
          \coordinate (NW) at (current page.north west);
          \coordinate (NE) at (current page.north east);

          {cornell_watermark_latex(
              document,
              asset_paths_by_id=asset_paths_by_id,
              page_number=page_number,
          )}

        {dedent(background_block).strip()}

          \draw[line width=.4pt] ($(SW)+(0,2in)$) -- ($(SE)+(0,2in)$);
          \draw[line width=.4pt] ($(SW)+(2.4in,2in)$) -- ($(NW)+(2.4in,0)$);

          {_region_scope_latex(page, "cue", page_number=page_number, fit_report=fit_report, asset_paths_by_id=asset_paths_by_id)}

          {_region_scope_latex(page, "main", page_number=page_number, fit_report=fit_report, asset_paths_by_id=asset_paths_by_id)}

          {_region_scope_latex(page, "summary", page_number=page_number, fit_report=fit_report, asset_paths_by_id=asset_paths_by_id)}

          {cornell_attribution_latex(document)}
        \end{{tikzpicture}}
        """
    ).strip() + "\n"


def _generate_document_tex(
    document: CornellDocument,
    *,
    fit_report: CornellFitReport | None = None,
    asset_paths_by_id: Mapping[str, str] | None = None,
    lines_image_path: str | None = LINES_IMAGE_INCLUDE_PATH,
) -> str:
    pages = document.ordered_pages()
    if not pages:
        raise ValueError("CornellDocument must contain at least one page")
    if fit_report is None:
        fit_report = default_cornell_fit_report(document)
    hybrid_sheet = is_hybrid_compact_template(document.template_id)
    page_bodies = [
        (
            _cornell_hybrid_sheet_page_body(
                document,
                page,
                page_number=index,
                fit_report=fit_report,
                asset_paths_by_id=asset_paths_by_id,
            )
            if hybrid_sheet
            else _cornell_page_body(
                document,
                page,
                page_number=index,
                fit_report=fit_report,
                asset_paths_by_id=asset_paths_by_id,
                lines_image_path=lines_image_path,
            )
        ).strip()
        for index, page in enumerate(pages, start=1)
    ]
    return (
        _latex_preamble(include_svg=latex_uses_svg_paths(dict(asset_paths_by_id or {})))
        + ("\n" + _cornell_hybrid_sheet_style_latex() if hybrid_sheet else "")
        + "\n\n\\begin{document}\n"
        + "\n\\clearpage\n".join(page_bodies)
        + "\n\\end{document}\n"
    )


def generate_cornell_tex(
    page: CornellPage,
    *,
    fit_report: CornellFitReport | None = None,
    asset_paths_by_id: Mapping[str, str] | None = None,
    lines_image_path: str | None = LINES_IMAGE_INCLUDE_PATH,
) -> str:
    """Generate the one-page LaTeX source for a Cornell page."""
    document = CornellDocument(schema_version=1, template_id="source_generation", pages=(page,))
    return _generate_document_tex(
        document,
        fit_report=fit_report,
        asset_paths_by_id=asset_paths_by_id,
        lines_image_path=lines_image_path,
    )


def generate_cornell_document_tex(
    document: CornellDocument,
    *,
    fit_report: CornellFitReport | None = None,
    asset_paths_by_id: Mapping[str, str] | None = None,
    lines_image_path: str | None = LINES_IMAGE_INCLUDE_PATH,
) -> str:
    """Generate a single LaTeX document for all Cornell pages in order."""
    return _generate_document_tex(
        document,
        fit_report=fit_report,
        asset_paths_by_id=asset_paths_by_id,
        lines_image_path=lines_image_path,
    )


def _prepare_output_dir(
    output_dir: str | Path,
    document: CornellDocument | None = None,
    *,
    db: Any | None = None,
    assets_by_id: Mapping[str, Mapping[str, Any]] | None = None,
    warnings: list[str] | None = None,
) -> tuple[Path, dict[str, str]]:
    output_path = Path(output_dir)
    output_path.mkdir(parents=True, exist_ok=True)
    assets_path = output_path / ASSETS_DIRNAME
    assets_path.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(HISTORICAL_LINES_IMAGE, assets_path / LINES_IMAGE_FILENAME)
    shutil.copyfile(
        PROJECT_ROOT / "templates_latex" / "mathmongo-macros.sty",
        output_path / "mathmongo-macros.sty",
    )
    image_paths = {}
    if document is not None:
        image_paths = prepare_cornell_image_assets(
            document,
            output_path,
            db=db,
            assets_by_id=assets_by_id,
            warnings=warnings,
        )
    return output_path, image_paths


def write_cornell_tex(
    page: CornellPage,
    output_dir: str | Path,
    *,
    fit_report: CornellFitReport | None = None,
    db: Any | None = None,
    assets_by_id: Mapping[str, Mapping[str, Any]] | None = None,
) -> Path:
    """Write a Cornell page source file and its renderer asset."""
    document = CornellDocument(schema_version=1, template_id="single_page_render", pages=(page,))
    output_path, image_paths = _prepare_output_dir(
        output_dir,
        document,
        db=db,
        assets_by_id=assets_by_id,
    )

    tex_path = output_path / f"cornell_{_slugify_page_id(page.page_id)}.tex"
    tex_path.write_text(
        generate_cornell_tex(page, fit_report=fit_report, asset_paths_by_id=image_paths),
        encoding="utf-8",
    )
    return tex_path


